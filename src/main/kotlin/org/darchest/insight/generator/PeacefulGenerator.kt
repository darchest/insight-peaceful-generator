package org.darchest.insight.generator

import mu.KotlinLogging
import org.darchest.insight.ConnectionManager
import org.darchest.insight.Table
import org.darchest.insight.Vendor
import java.sql.Connection
import kotlin.time.TimeSource

class PeacefulGenerator {

    private val logger = KotlinLogging.logger {}
    private val schemaAnalyzer = RealSchemaAnalyzer()
    private val planBuilder = ModificationPlanBuilder()

    /** Includes all registered tables, even those with @Generatable(actions = 0). */
    val tables: MutableList<() -> Table> = mutableListOf()
    /** Fill these lists manually or call an init<GenPack>() extension generated by KSP. */
    val recordsSources: MutableList<() -> RecordsSource<*>> = mutableListOf()

    suspend fun generate() {
        withTiming("Генерация (общее время)") {
            val configuredTables = withTiming("Подготовка таблиц") {
                tables.map { it() }.distinctBy { it.schemaName to it.sqlName }
            }
            require(configuredTables.isNotEmpty()) {
                "No tables configured; call init<GenPack>() or fill the generator's tables manually"
            }
            val tables = configuredTables.filter { it.generationActions() and Generatable.ALL != 0 }
            if (tables.isEmpty()) {
                logger.info { "Для зарегистрированных таблиц генерация отключена" }
                return@withTiming
            }
            val sources = withTiming("Подготовка источников записей") {
                recordsSources.map { it() }
            }
            val (conn, vendor) = withTiming("Подготовка подключения") {
                val connections = tables.map { it.connectionName }.distinct()
                require(connections.size == 1) { "A generation pack must use one connection" }
                ConnectionManager.getConnection(connections.single()) to ConnectionManager.getVendor(connections.single())
            }
            // Create all schemas' tables before inserting any cross-schema seed records.
            val targets = withTiming("Подготовка описаний схем") {
                tables.filter { it.generationActions() and Generatable.SCHEMA != 0 }
                    .groupBy { it.schemaName ?: conn.schema ?: "public" }
                    .map { (name, items) -> items.toSchemaDescriptor(name, vendor) }
            }
            val plans = targets.map { target ->
                withTiming("Проверка идентификаторов схемы ${target.name}") {
                    SchemaIdentifierValidator.validate(target, vendor)
                }
                val current = withTiming("Анализ схемы ${target.name}") {
                    schemaAnalyzer.analyze(conn, target.name)
                }
                withTiming("Построение плана изменений схемы ${target.name}") {
                    planBuilder.build(current, target).also { logPlan(target.name, it) }
                }
            }
            plans.forEachIndexed { i, plan ->
                inSchema(conn, targets[i].name) {
                    executePlan(conn, targets[i].name,
                        ModificationPlan(plan.modifications.filter { m -> m.kind != ModificationKind.ADD_FOREIGN_KEY }))
                }
            }
            withTiming("Создание/обновление записей (${sources.size} источников)") {
                val tableActions = configuredTables.associate { tableKey(it) to it.generationActions() }
                RecordsGenerator.generate(conn, sources, vendor) { table ->
                    tableActions[tableKey(table)] ?: table.generationActions()
                }
            }
            plans.forEachIndexed { i, plan ->
                inSchema(conn, targets[i].name) {
                    executePlan(conn, targets[i].name,
                        ModificationPlan(plan.modifications.filter { m -> m.kind == ModificationKind.ADD_FOREIGN_KEY }))
                }
            }
            targets.forEach { target ->
                withTiming("Проверка результата генерации схемы ${target.name}") {
                    logResult(target.name, planBuilder.build(schemaAnalyzer.analyze(conn, target.name), target))
                }
            }
        }
    }

    suspend fun generate(conn: Connection, targetSchema: SchemaDescriptor, vendor: Vendor) {
        generate(conn, targetSchema, vendor, emptyList())
    }

    suspend fun generate(conn: Connection, targetSchema: SchemaDescriptor, vendor: Vendor, recordsSources: List<RecordsSource<*>>) {
        withTiming("Генерация схемы ${targetSchema.name} (общее время)") {
            val target = targetSchema.copy(tables = targetSchema.tables.filter { it.actions and Generatable.SCHEMA != 0 })
            val sources = if (targetSchema.tables.any { it.actions and Generatable.RECORDS != 0 }) recordsSources else emptyList()
            if (target.tables.isEmpty() && sources.isEmpty()) return@withTiming
            val plan = if (target.tables.isEmpty()) ModificationPlan(emptyList()) else {
                withTiming("Проверка идентификаторов схемы ${target.name}") {
                    SchemaIdentifierValidator.validate(target, vendor)
                }
                val current = withTiming("Анализ схемы ${target.name}") {
                    schemaAnalyzer.analyze(conn, target.name)
                }
                withTiming("Построение плана изменений схемы ${target.name}") {
                    planBuilder.build(current, target).also { logPlan(target.name, it) }
                }
            }

            inSchema(conn, targetSchema.name) {
                executePlan(conn, targetSchema.name,
                    ModificationPlan(plan.modifications.filter { it.kind != ModificationKind.ADD_FOREIGN_KEY }))
                withTiming("Создание/обновление записей схемы ${targetSchema.name} (${sources.size} источников)") {
                    val tableActions = targetSchema.tables.associate { it.name to it.actions }
                    RecordsGenerator.generate(conn, sources, vendor) { table ->
                        if (table.schemaName == null || table.schemaName == targetSchema.name)
                            tableActions[table.sqlName] ?: table.generationActions()
                        else table.generationActions()
                    }
                }
                executePlan(conn, targetSchema.name,
                    ModificationPlan(plan.modifications.filter { it.kind == ModificationKind.ADD_FOREIGN_KEY }))
            }

            if (target.tables.isNotEmpty()) {
                withTiming("Проверка результата генерации схемы ${target.name}") {
                    val remaining = planBuilder.build(schemaAnalyzer.analyze(conn, target.name), target)
                    logResult(target.name, remaining)
                }
            }
        }
    }

    private fun tableKey(table: Table) = Triple(table.connectionName, table.schemaName, table.sqlName)

    private suspend fun <T> withTiming(stage: String, block: suspend () -> T): T {
        val startedAt = TimeSource.Monotonic.markNow()
        logger.info { "$stage: начало" }
        var completed = false
        try {
            val result = block()
            completed = true
            return result
        } finally {
            val elapsed = startedAt.elapsedNow()
            if (completed) {
                logger.info { "$stage: время выполнения $elapsed" }
            } else {
                logger.warn { "$stage: прервано, время выполнения $elapsed" }
            }
        }
    }

    private suspend fun inSchema(conn: Connection, name: String, block: suspend () -> Unit) {
        val previous = conn.schema
        try {
            conn.schema = name
            block()
        } finally {
            conn.schema = previous
        }
    }

    private fun logPlan(schemaName: String, plan: ModificationPlan) {
        if (plan.modifications.isEmpty()) {
            logger.info { "Изменений для схемы $schemaName не требуется" }
            return
        }
        logger.info { "План изменений схемы $schemaName (${plan.modifications.size} шагов):" }
        plan.modifications.forEach { modification ->
            logger.info { "- ${modification.description}" }
            logger.debug { modification.sql }
        }
    }

    private suspend fun executePlan(conn: Connection, schemaName: String, plan: ModificationPlan) {
        plan.modifications.groupBy { it.kind }.forEach { (kind, modifications) ->
            val stage = when (kind) {
                ModificationKind.CREATE_TABLE -> "Создание таблиц"
                ModificationKind.ADD_COLUMN -> "Добавление столбцов"
                ModificationKind.ALTER_COLUMN_SIZE -> "Изменение размеров столбцов"
                ModificationKind.ADD_INDEX -> "Генерация индексов"
                ModificationKind.ADD_FOREIGN_KEY -> "Добавление внешних ключей"
            }
            withTiming("$stage схемы $schemaName (${modifications.size} изменений)") {
                modifications.forEach { modification ->
                    logger.debug { modification.sql }
                    conn.createStatement().use { statement ->
                        statement.execute(modification.sql)
                    }
                }
            }
        }
    }

    private fun logResult(schemaName: String, remainingPlan: ModificationPlan) {
        if (remainingPlan.modifications.isEmpty()) {
            logger.info { "Схема $schemaName приведена к ожидаемому состоянию" }
            return
        }
        logger.warn {
            "Схема $schemaName не полностью соответствует ожидаемому состоянию, осталось изменений: ${remainingPlan.modifications.size}"
        }
        remainingPlan.modifications.forEach { modification ->
            logger.warn { "- ${modification.description}" }
        }
    }
}
